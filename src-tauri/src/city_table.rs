/// 去掉行政后缀：「北京市」→「北京」、「朝阳区」→「朝阳」
fn strip_suffix(name: &str) -> String {
    for suffix in [
        "特别行政区",
        "自治区",
        "自治州",
        "地区",
        "盟",
        "省",
        "市",
        "区",
        "县",
        "旗",
    ] {
        if let Some(stripped) = name.strip_suffix(suffix) {
            return stripped.to_string();
        }
    }
    name.to_string()
}

fn table() -> &'static Vec<CityCoord> {
    static TABLE: OnceLock<Vec<CityCoord>> = OnceLock::new();
    TABLE.get_or_init(|| {
        CITY_TABLE
            .lines()
            .filter_map(|line| {
                let mut parts = line.split_whitespace();
                let name = parts.next()?.to_string();
                let lon: f64 = parts.next()?.parse().ok()?;
                let lat: f64 = parts.next()?.parse().ok()?;
                let stripped = strip_suffix(&name);
                Some(CityCoord {
                    name,
                    lat,
                    lon,
                    stripped,
                })
            })
            .collect()
    })
}

/// 按名称查城市坐标：原名完全一致优先，其次去后缀名（如「杭州」可匹配「杭州市」）。
/// 两轮匹配合并为一次遍历；返回表中数据而非克隆，避免每次命中复制两个 String。
pub fn lookup(query: &str) -> Option<&'static CityCoord> {
    let query = query.trim();
    if query.is_empty() {
        return None;
    }
    let query_stripped = strip_suffix(query);

    let mut stripped_match = None;
    for coord in table().iter() {
        if coord.name == query {
            return Some(coord);
        }
        if stripped_match.is_none() && coord.stripped == query_stripped {
            stripped_match = Some(coord);
        }
    }
    stripped_match
}
